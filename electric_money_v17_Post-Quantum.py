class MerkleTree:
    @staticmethod
    def compute_root(items: List[str]) -> str:
        if not items:
            return sha3_512_hex(b"")
        level = [str(x) for x in items]
        while len(level) > 1:
            if len(level) % 2:
                level.append(level[-1])
            level = [
                sha3_512_hex((level[i] + level[i + 1]).encode("ascii"))
                for i in range(0, len(level), 2)
            ]
        return level[0]


