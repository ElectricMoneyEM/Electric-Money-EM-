@dataclass
class L2Transaction:
    sender_pubkey: str
    recipient: str
    amount: int
    nonce: int
    timestamp: int
    signature: str = ""
    tx_id: str = ""

    def sender(self) -> str:
        return Wallet.address_from_pubkey(self.sender_pubkey)

    def signing_dict(self) -> Dict[str, Any]:
        return {
            "sender_pubkey": self.sender_pubkey,
            "recipient": self.recipient,
            "amount": self.amount,
            "nonce": self.nonce,
            "timestamp": self.timestamp,
        }

    def signing_bytes(self) -> bytes:
        return canonical_json(self.signing_dict())

    def calculate_id(self) -> str:
        return hash_obj({
            **self.signing_dict(),
            "signature": self.signature,
        })

    def valid(self) -> bool:
        return (
            self.amount > 0
            and is_hex(self.sender_pubkey, Wallet.PUBLIC_KEY_HEX_LENGTH)
            and is_hex(self.recipient, 128)
            and self.signature != ""
            and self.tx_id == self.calculate_id()
            and Wallet.verify(
                self.sender_pubkey, self.signing_bytes(), self.signature
            )
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            **self.signing_dict(),
            "signature": self.signature,
            "tx_id": self.tx_id,
        }


class Layer2Sequencer:
    """
    Reference L2.

    L1 does NOT execute this state transition. L1 only commits the batch root
    and state root. Therefore this is not a trustless rollup.

    Deposit model:
      - an L1 user sends CA to L2_BRIDGE_ADDRESS through a normal L1 transfer
      - after confirmation, the sequencer can credit the corresponding net amount
      - withdrawals are operator-controlled in this prototype
    """

    def __init__(self, l1: Blockchain):
        self.l1 = l1
        self.balances: Dict[str, int] = {}
        self.nonces: Dict[str, int] = {}
        self.mempool: List[L2Transaction] = []
        self.sequence = 0
        self.poh_hash = sha3_512_hex(b"EM_L2_POH_GENESIS")
        self.pending_commitments: List[Dict[str, Any]] = []

    def _state_root(self) -> str:
        state = {
            "balances": dict(sorted(self.balances.items())),
            "nonces": dict(sorted(self.nonces.items())),
        }
        return hash_obj(state)

    def process_l1_deposit(self, address: str, amount: int) -> bool:
        if amount <= 0:
            return False
        # The caller is expected to have observed a confirmed L1 transfer
        # to the bridge. We do not mutate L1 state here.
        self.balances[address] = self.balances.get(address, 0) + amount
        return True

    def add_signed_tx(self, tx: L2Transaction) -> bool:
        if not tx.valid():
            return False

        sender = tx.sender()
        if tx.nonce != self.nonces.get(sender, 0):
            return False
        if self.balances.get(sender, 0) < tx.amount:
            return False

        self.balances[sender] -= tx.amount
        self.balances[tx.recipient] = self.balances.get(tx.recipient, 0) + tx.amount
        self.nonces[sender] = tx.nonce + 1

        self.sequence += 1
        self.poh_hash = sha3_512_hex(
            (self.poh_hash + tx.tx_id).encode("ascii")
        )
        self.mempool.append(tx)
        return True

    def commit_batch(self) -> Optional[Dict[str, Any]]:
        if not self.mempool:
            return None

        ids = [tx.tx_id for tx in self.mempool]
        commitment = {
            "root": MerkleTree.compute_root(ids),
            "count": len(ids),
            "first_sequence": self.sequence - len(ids) + 1,
            "last_sequence": self.sequence,
            "state_root": self._state_root(),
        }
        self.mempool.clear()
        self.pending_commitments.append(commitment)
        return commitment

    def take_commitments(self) -> List[Dict[str, Any]]:
        result = list(self.pending_commitments)
        self.pending_commitments.clear()
        return result


