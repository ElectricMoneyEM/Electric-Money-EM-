@dataclass
class Transaction:
    sender_pubkey: str
    recipient: str
    amount: int
    nonce: int
    timestamp: int
    signature: str = ""
    tx_id: str = ""

    def sender_address(self) -> str:
        return Wallet.address_from_pubkey(self.sender_pubkey)

    def burned(self) -> int:
        return (self.amount * TX_BURN_BPS) // 10_000

    def receiver_tax(self) -> int:
        # Treasury portion of the incoming-payment levy.
        return (self.amount * RECEIVER_TAX_BPS) // 10_000

    def net_amount(self) -> int:
        # Sender pays the full amount; Treasury gets 0.20% and 0.05% is burned.
        return self.amount - self.receiver_tax() - self.burned()

    def signing_dict(self) -> Dict[str, Any]:
        return {
            "sender_pubkey": self.sender_pubkey,
            "recipient": self.recipient,
            "amount": self.amount,
            "nonce": self.nonce,
            "timestamp": self.timestamp,
        }

    def signing_bytes(self) -> bytes:
        return canonical_json(self.signing_dict())

    def calculate_id(self) -> str:
        return hash_obj({
            **self.signing_dict(),
            "signature": self.signature,
        })

    def is_valid(
        self,
        now: Optional[int] = None,
        *,
        check_age: bool = True,
    ) -> bool:
        try:
            now = int(time.time()) if now is None else now
            checked_amount(self.amount)

            if self.nonce < 0:
                return False
            if not is_hex(self.sender_pubkey, Wallet.PUBLIC_KEY_HEX_LENGTH):
                return False
            if not isinstance(self.recipient, str) or len(self.recipient) != 128:
                return False
            if not is_hex(self.recipient, 128):
                return False
            if self.recipient == "SYSTEM":
                return False
            if check_age and self.timestamp < now - MAX_TX_AGE:
                return False
            if self.timestamp > now + MAX_FUTURE_BLOCK_TIME:
                return False
            if not self.signature or not is_hex(self.signature):
                return False

            expected_id = self.calculate_id()
            if self.tx_id != expected_id:
                return False

            return Wallet.verify(
                self.sender_pubkey,
                self.signing_bytes(),
                self.signature,
            )
        except (ValueError, TypeError):
            return False

    def to_dict(self) -> Dict[str, Any]:
        return {
            **self.signing_dict(),
            "signature": self.signature,
            "tx_id": self.tx_id or self.calculate_id(),
        }

    @staticmethod
    def from_dict(d: Dict[str, Any]) -> "Transaction":
        return Transaction(
            sender_pubkey=d["sender_pubkey"],
            recipient=d["recipient"],
            amount=int(d["amount"]),
            nonce=int(d["nonce"]),
            timestamp=int(d["timestamp"]),
            signature=d.get("signature", ""),
            tx_id=d.get("tx_id", ""),
        )


