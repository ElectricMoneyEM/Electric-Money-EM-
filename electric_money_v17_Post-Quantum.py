@dataclass
class MiningShare:
    miner: str
    job_id: str
    difficulty: int
    nonce: int
    share_hash: str = ""
    share_id: str = ""

    @staticmethod
    def challenge(job_id: str, difficulty: int) -> str:
        return sha3_512_hex(
            f"ELECTRIC-MONEY-SHARE-{NETWORK_ID}-{job_id}-{difficulty}".encode("ascii")
        )

    def calculate_hash(self) -> str:
        payload = (self.challenge(self.job_id, self.difficulty) + self.miner + str(self.nonce)).encode("ascii")
        return sha3_512_hex(payload)

    def calculate_id(self) -> str:
        return hash_obj({
            "type": "mining_share",
            "miner": self.miner,
            "job_id": self.job_id,
            "difficulty": self.difficulty,
            "nonce": self.nonce,
            "share_hash": self.share_hash,
        })

    def is_valid(self, expected_job_id: Optional[str] = None, expected_difficulty: Optional[int] = None) -> bool:
        if not is_hex(self.miner, 128):
            return False
        if not is_hex(self.job_id, 128):
            return False
        if self.difficulty < MINING_SHARE_MIN_DIFFICULTY or self.nonce < 0:
            return False
        if expected_job_id is not None and self.job_id != expected_job_id:
            return False
        if expected_difficulty is not None and self.difficulty != expected_difficulty:
            return False
        expected = self.calculate_hash()
        if self.share_hash != expected:
            return False
        if not expected.startswith("0" * self.difficulty):
            return False
        return self.share_id == self.calculate_id()

    def to_dict(self) -> Dict[str, Any]:
        return {
            "type": "mining_share",
            "miner": self.miner,
            "job_id": self.job_id,
            "difficulty": self.difficulty,
            "nonce": self.nonce,
            "share_hash": self.share_hash,
            "share_id": self.share_id or self.calculate_id(),
        }

    @staticmethod
    def from_dict(d: Dict[str, Any]) -> "MiningShare":
        return MiningShare(
            miner=d["miner"],
            job_id=d["job_id"],
            difficulty=int(d["difficulty"]),
            nonce=int(d["nonce"]),
            share_hash=d.get("share_hash", ""),
            share_id=d.get("share_id", ""),
        )


