def send_frame(conn: socket.socket, obj: Any) -> None:
    payload = canonical_json(obj)
    if len(payload) > MAX_FRAME_BYTES:
        raise ValueError("message too large")
    conn.sendall(struct.pack("!I", len(payload)) + payload)


def _recv_exact(conn: socket.socket, n: int) -> bytes:
    chunks = []
    remaining = n
    while remaining:
        chunk = conn.recv(remaining)
        if not chunk:
            return b""
        chunks.append(chunk)
        remaining -= len(chunk)
    return b"".join(chunks)


def recv_frame(conn: socket.socket) -> Optional[Any]:
    header = _recv_exact(conn, 4)
    if not header:
        return None
    length = struct.unpack("!I", header)[0]
    if length <= 0 or length > MAX_FRAME_BYTES:
        raise ValueError("invalid frame size")
    payload = _recv_exact(conn, length)
    if not payload:
        return None
    return json.loads(payload.decode("utf-8"))


def parse_peer(value: str) -> Tuple[str, int]:
    host, port = value.rsplit(":", 1)
    return host, int(port)


class P2PNode:
    def __init__(
        self,
        bc: Blockchain,
        host: str = "0.0.0.0",
        port: int = 5000,
        peers: Optional[List[str]] = None,
        node_id: Optional[str] = None,
    ):
        self.bc = bc
        self.host = host
        self.port = port
        self.node_id = node_id or secrets.token_hex(16)
        self.peers = set()
        for peer in (peers or []):
            try:
                host, port = parse_peer(peer)
                if host and 1 <= port <= 65535 and len(self.peers) < MAX_PEERS:
                    self.peers.add(f"{host}:{port}")
            except (ValueError, TypeError):
                continue
        self.running = False
        self.server: Optional[socket.socket] = None

        self.seen_txs = BoundedSeenSet(MAX_SEEN_TX_IDS)
        self.seen_shares = BoundedSeenSet(MAX_SEEN_SHARE_IDS)
        self.seen_blocks = BoundedSeenSet(MAX_SEEN_BLOCK_IDS)
        self.peer_lock = threading.RLock()
        self.connection_slots = threading.BoundedSemaphore(64)

    def hello(self) -> Dict[str, Any]:
        return {
            "type": "HELLO",
            "protocol_version": PROTOCOL_VERSION,
            "network_id": NETWORK_ID,
            "node_id": self.node_id,
            "height": self.bc.height,
            "tip": self.bc.chain[-1].block_hash,
            "work": str(self.bc.cumulative_work),
        }

    def start(self) -> None:
        if self.running:
            return

        self.server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.server.bind((self.host, self.port))
        self.server.listen(64)
        self.running = True

        threading.Thread(target=self._accept_loop, daemon=True).start()
        threading.Thread(target=self._peer_loop, daemon=True).start()

        print(
            f"[P2P] node={self.node_id} listening on "
            f"{self.host}:{self.port}, peers={sorted(self.peers)}"
        )

    def stop(self) -> None:
        self.running = False
        if self.server:
            try:
                self.server.close()
            except OSError:
                pass

    def _accept_loop(self) -> None:
        assert self.server is not None
        while self.running:
            try:
                conn, addr = self.server.accept()
                if not self.connection_slots.acquire(blocking=False):
                    conn.close()
                    continue
                threading.Thread(
                    target=self._handle_connection,
                    args=(conn, addr),
                    daemon=True,
                ).start()
            except OSError:
                break

    def _peer_loop(self) -> None:
        while self.running:
            for peer in list(self.peers):
                try:
                    self._connect(peer)
                except Exception:
                    pass
            time.sleep(5)

    def _connect(self, peer: str) -> None:
        host, port = parse_peer(peer)
        with socket.create_connection((host, port), timeout=3) as conn:
            conn.settimeout(8)
            send_frame(conn, self.hello())
            reply = recv_frame(conn)
            if reply:
                self._process_message(reply, conn, peer)

    def _handle_connection(
        self, conn: socket.socket, addr: Tuple[str, int]
    ) -> None:
        conn.settimeout(10)
        peer_name = f"{addr[0]}:{addr[1]}"
        try:
            msg = recv_frame(conn)
            if msg:
                self._process_message(msg, conn, peer_name)
        except Exception as e:
            print(f"[P2P] {peer_name}: {e}")
        finally:
            try:
                conn.close()
            except OSError:
                pass
            finally:
                self.connection_slots.release()

    def _process_message(
        self,
        msg: Dict[str, Any],
        conn: socket.socket,
        peer_name: str,
    ) -> None:
        if not isinstance(msg, dict):
            return
        mtype = msg.get("type")

        if mtype == "HELLO":
            if msg.get("network_id") != NETWORK_ID:
                return
            if int(msg.get("protocol_version", -1)) != PROTOCOL_VERSION:
                return
            remote_node_id = msg.get("node_id")
            if not isinstance(remote_node_id, str) or not remote_node_id or remote_node_id == self.node_id:
                return

            remote_work = int(msg.get("work", "0"))
            send_frame(conn, self.hello())

            if remote_work > self.bc.cumulative_work:
                send_frame(conn, {
                    "type": "GET_CHAIN",
                    "from_height": 0,
                })
            return

        if mtype == "GET_CHAIN":
            send_frame(conn, {
                "type": "CHAIN",
                "chain": [b.to_dict() for b in self.bc.chain],
            })
            return

        if mtype == "CHAIN":
            raw_chain = msg.get("chain", [])
            if not isinstance(raw_chain, list):
                return
            try:
                candidate = [Block.from_dict(x) for x in raw_chain]
            except (KeyError, TypeError, ValueError):
                return
            if self.bc.try_replace_chain(candidate):
                print(
                    f"[P2P] adopted heavier chain height={self.bc.height} "
                    f"work={self.bc.cumulative_work}"
                )
            return

        if mtype == "TX":
            try:
                tx = Transaction.from_dict(msg["tx"])
            except (KeyError, TypeError, ValueError):
                return
            if tx.tx_id in self.seen_txs:
                return
            if self.bc.add_transaction(tx):
                self.seen_txs.add(tx.tx_id)
                self.broadcast_tx(tx, exclude=peer_name)
            return

        if mtype == "SHARE":
            try:
                share = MiningShare.from_dict(msg["share"])
            except (KeyError, ValueError, TypeError):
                return
            if share.share_id in self.seen_shares:
                return
            if self.bc.add_mining_share(share):
                self.seen_shares.add(share.share_id)
                self.broadcast_share(share, exclude=peer_name)
            return

        if mtype == "BLOCK":
            try:
                block = Block.from_dict(msg["block"])
            except (KeyError, TypeError, ValueError):
                return
            if block.block_hash in self.seen_blocks:
                return
            self.seen_blocks.add(block.block_hash)

            result = self.bc.receive_block(block)
            if result in ("reorged", "known", "valid-lighter"):
                self.broadcast_block(block, exclude=peer_name)
            elif result == "orphan":
                # Ask the peer for the full chain; validation will decide.
                try:
                    send_frame(conn, {"type": "GET_CHAIN", "from_height": 0})
                except Exception:
                    pass
            return

        if mtype == "PING":
            send_frame(conn, {"type": "PONG"})
            return

    def _send_peer(self, peer: str, message: Dict[str, Any]) -> None:
        host, port = parse_peer(peer)
        try:
            with socket.create_connection((host, port), timeout=3) as conn:
                conn.settimeout(8)
                send_frame(conn, message)
        except OSError:
            pass

    def broadcast_tx(self, tx: Transaction, exclude: Optional[str] = None) -> None:
        message = {"type": "TX", "tx": tx.to_dict()}
        for peer in list(self.peers):
            if peer != exclude:
                threading.Thread(
                    target=self._send_peer,
                    args=(peer, message),
                    daemon=True,
                ).start()

    def broadcast_share(self, share: MiningShare, exclude: Optional[str] = None) -> None:
        message = {"type": "SHARE", "share": share.to_dict()}
        for peer in list(self.peers):
            if peer != exclude:
                threading.Thread(
                    target=self._send_peer,
                    args=(peer, message),
                    daemon=True,
                ).start()

    def broadcast_block(self, block: Block, exclude: Optional[str] = None) -> None:
        message = {"type": "BLOCK", "block": block.to_dict()}
        for peer in list(self.peers):
            if peer != exclude:
                threading.Thread(
                    target=self._send_peer,
                    args=(peer, message),
                    daemon=True,
                ).start()

    def broadcast_chain(self) -> None:
        message = {
            "type": "CHAIN",
            "chain": [b.to_dict() for b in self.bc.chain],
        }
        for peer in list(self.peers):
            threading.Thread(
                target=self._send_peer,
                args=(peer, message),
                daemon=True,
            ).start()


