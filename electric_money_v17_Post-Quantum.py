@dataclass
class Block:
    index: int
    previous_hash: str
    transactions: List[Dict[str, Any]]
    timestamp: int
    nonce: int
    difficulty: int
    merkle_root: str
    extra_data: str
    block_hash: str = ""

    def header_dict(self) -> Dict[str, Any]:
        return {
            "index": self.index,
            "previous_hash": self.previous_hash,
            "merkle_root": self.merkle_root,
            "timestamp": self.timestamp,
            "nonce": self.nonce,
            "difficulty": self.difficulty,
            "extra_data": self.extra_data,
        }

    def calculate_hash(self) -> str:
        return hash_obj(self.header_dict())

    def mine(self, stop_event: Optional[threading.Event] = None) -> None:
        target = "0" * self.difficulty
        while True:
            if stop_event and stop_event.is_set():
                raise RuntimeError("mining interrupted")
            self.block_hash = self.calculate_hash()
            if self.block_hash.startswith(target):
                return
            self.nonce += 1

    def to_dict(self) -> Dict[str, Any]:
        return {
            **self.header_dict(),
            "hash": self.block_hash,
            "transactions": self.transactions,
        }

    @staticmethod
    def from_dict(d: Dict[str, Any]) -> "Block":
        return Block(
            index=int(d["index"]),
            previous_hash=d["previous_hash"],
            transactions=list(d["transactions"]),
            timestamp=int(d["timestamp"]),
            nonce=int(d["nonce"]),
            difficulty=int(d["difficulty"]),
            merkle_root=d["merkle_root"],
            extra_data=d.get("extra_data", ""),
            block_hash=d.get("hash", ""),
        )


