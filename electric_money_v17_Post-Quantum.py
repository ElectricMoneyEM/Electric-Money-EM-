# HASH / SERIALIZATION
# ============================================================
# SHA3-512 is retained unchanged from V15. Quantum computers may offer a
# generic quadratic Grover speedup, but no practical attack is known against
# SHA3-512; the critical V15 quantum weakness was ECDSA/secp256k1.


def sha3_512_hex(data: bytes) -> str:
    return hashlib.sha3_512(data).hexdigest()


def canonical_json(obj: Any) -> bytes:
    return json.dumps(
        obj,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")


def hash_obj(obj: Any) -> str:
    return sha3_512_hex(canonical_json(obj))


def checked_amount(value: int) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise ValueError("amount must be an integer base-unit value")
    if value <= 0 or value > MAX_TX_AMOUNT:
        raise ValueError("amount outside allowed range")
    return value


def is_hex(value: str, length: Optional[int] = None) -> bool:
    if not isinstance(value, str):
        return False
    if length is not None and len(value) != length:
        return False
    try:
        bytes.fromhex(value)
        return True
    except (ValueError, TypeError):
        return False


