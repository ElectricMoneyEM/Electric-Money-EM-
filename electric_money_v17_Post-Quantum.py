class Wallet:
    """ML-DSA-65 wallet.

    V16 replaces the V15 secp256k1/ECDSA signing system with ML-DSA-65,
    standardized by NIST as a post-quantum digital signature scheme.

    The private key is stored in PKCS#8 DER bytes and the public key field
    carries the raw ML-DSA-65 public key (1952 bytes, hex encoded). OpenSSL
    3.5+ is used as the backend because the Python environment does not need
    to depend on a non-standard PQ package.
    """

    PUBLIC_KEY_HEX_LENGTH = MLDSA65_PUBLIC_KEY_BYTES * 2
    SIGNATURE_HEX_LENGTH = MLDSA65_SIGNATURE_BYTES * 2

    @staticmethod
    def _require_backend() -> None:
        openssl = shutil.which("openssl")
        if not openssl:
            raise RuntimeError(
                "OpenSSL 3.5+ is required for ML-DSA-65 wallets"
            )
        try:
            version = subprocess.run(
                [openssl, "version"],
                capture_output=True,
                text=True,
                check=True,
                timeout=5,
            ).stdout.strip()
        except (OSError, subprocess.SubprocessError) as exc:
            raise RuntimeError("unable to execute OpenSSL") from exc
        # OpenSSL 3.5 introduced the ML-DSA command-line provider support used
        # by this reference implementation. Reject older versions explicitly.
        try:
            major, minor = [int(x) for x in version.split()[1].split(".")[:2]]
        except (IndexError, ValueError):
            raise RuntimeError(f"unable to parse OpenSSL version: {version}")
        if (major, minor) < (3, 5):
            raise RuntimeError(
                f"OpenSSL 3.5+ required for {PQ_SIGNATURE_ALGORITHM}; found {version}"
            )

    @staticmethod
    def _run_openssl(args: List[str], timeout: int = 15) -> subprocess.CompletedProcess:
        Wallet._require_backend()
        try:
            return subprocess.run(
                ["openssl", *args],
                capture_output=True,
                check=True,
                timeout=timeout,
            )
        except subprocess.CalledProcessError as exc:
            detail = exc.stderr.decode("utf-8", errors="replace").strip()
            raise RuntimeError(f"OpenSSL operation failed: {detail}") from exc
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise RuntimeError("OpenSSL operation failed") from exc

    @staticmethod
    def _extract_raw_public_key(spki_der: bytes) -> bytes:
        """Extract the raw ML-DSA public key from an X.509 SubjectPublicKeyInfo."""
        # ML-DSA-65 SPKI is a DER SEQUENCE ending in a BIT STRING whose
        # contents are one unused-bits byte followed by the 1952-byte key.
        marker = b"\x03\x82\x07\xa1\x00"
        pos = spki_der.rfind(marker)
        if pos < 0 or pos + len(marker) + MLDSA65_PUBLIC_KEY_BYTES != len(spki_der):
            raise RuntimeError("unexpected ML-DSA-65 public key encoding")
        return spki_der[pos + len(marker):]

    @staticmethod
    def _public_spki_from_raw(pubkey_hex: str) -> bytes:
        # Reconstruct the exact DER SubjectPublicKeyInfo used by OpenSSL for
        # ML-DSA-65: SEQUENCE { algorithmIdentifier, BIT STRING(public key) }.
        if not is_hex(pubkey_hex, Wallet.PUBLIC_KEY_HEX_LENGTH):
            raise ValueError("invalid ML-DSA-65 public key")
        raw = bytes.fromhex(pubkey_hex)
        # ML-DSA-65 OID: 2.16.840.1.101.3.4.3.18
        # AlgorithmIdentifier = SEQUENCE { OBJECT IDENTIFIER }
        alg = bytes.fromhex("300b0609608648016503040312")
        bit_string = bytes.fromhex("03 82 07 a1 00") + raw
        body = alg + bit_string
        # body length is 1970 bytes, encoded as 0x82 0x07 0xb2.
        return bytes.fromhex("30 82 07 b2") + body

    def __init__(self, private_key: Optional[bytes] = None):
        if private_key is not None and not isinstance(private_key, bytes):
            raise TypeError("private_key must be DER bytes")

        if private_key:
            self._private_key = bytes(private_key)
        else:
            result = self._run_openssl(
                ["genpkey", "-algorithm", PQ_SIGNATURE_ALGORITHM, "-outform", "DER"],
                timeout=30,
            )
            self._private_key = result.stdout

        if not self._private_key:
            raise RuntimeError("empty ML-DSA private key")

        with tempfile.TemporaryDirectory() as td:
            key_path = os.path.join(td, "key.der")
            pub_path = os.path.join(td, "pub.der")
            Path(key_path).write_bytes(self._private_key)
            self._run_openssl(
                [
                    "pkey", "-inform", "DER", "-in", key_path,
                    "-pubout", "-outform", "DER", "-out", pub_path,
                ]
            )
            spki = Path(pub_path).read_bytes()

        self.public_key_hex = self._extract_raw_public_key(spki).hex()
        self.address = sha3_512_hex(bytes.fromhex(self.public_key_hex))

    def sign(self, message: bytes) -> str:
        with tempfile.TemporaryDirectory() as td:
            key_path = os.path.join(td, "key.der")
            msg_path = os.path.join(td, "message.bin")
            sig_path = os.path.join(td, "signature.bin")
            Path(key_path).write_bytes(self._private_key)
            Path(msg_path).write_bytes(message)
            self._run_openssl(
                [
                    "pkeyutl", "-sign",
                    "-inkey", key_path, "-keyform", "DER",
                    "-in", msg_path, "-out", sig_path,
                ],
                timeout=30,
            )
            signature = Path(sig_path).read_bytes()
        if len(signature) != MLDSA65_SIGNATURE_BYTES:
            raise RuntimeError("unexpected ML-DSA-65 signature length")
        return signature.hex()

    def sign_transaction(self, tx: "Transaction") -> "Transaction":
        tx.signature = self.sign(tx.signing_bytes())
        tx.tx_id = tx.calculate_id()
        return tx

    @staticmethod
    def verify(pubkey_hex: str, message: bytes, signature_hex: str) -> bool:
        try:
            if not is_hex(pubkey_hex, Wallet.PUBLIC_KEY_HEX_LENGTH):
                return False
            if not is_hex(signature_hex, Wallet.SIGNATURE_HEX_LENGTH):
                return False
            pub_der = Wallet._public_spki_from_raw(pubkey_hex)
            with tempfile.TemporaryDirectory() as td:
                pub_path = os.path.join(td, "pub.der")
                msg_path = os.path.join(td, "message.bin")
                sig_path = os.path.join(td, "signature.bin")
                Path(pub_path).write_bytes(pub_der)
                Path(msg_path).write_bytes(message)
                Path(sig_path).write_bytes(bytes.fromhex(signature_hex))
                Wallet._require_backend()
                result = subprocess.run(
                    [
                        "openssl", "pkeyutl", "-verify", "-pubin",
                        "-inkey", pub_path, "-keyform", "DER",
                        "-in", msg_path, "-sigfile", sig_path,
                    ],
                    capture_output=True,
                    timeout=15,
                )
                return result.returncode == 0
        except (ValueError, TypeError, OSError, RuntimeError, subprocess.SubprocessError):
            return False

    @staticmethod
    def address_from_pubkey(pubkey_hex: str) -> str:
        if not is_hex(pubkey_hex, Wallet.PUBLIC_KEY_HEX_LENGTH):
            raise ValueError("invalid ML-DSA-65 public key")
        return sha3_512_hex(bytes.fromhex(pubkey_hex))


